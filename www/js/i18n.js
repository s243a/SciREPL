/**
 * i18n.js — localization: language detection, string lookup, RTL.
 *
 * Two decisions worth stating up front, because both came from a specific
 * concern: that a user picks their language and gets a mostly-English UI.
 *
 * 1. A locale is only offered once it is actually translated. Every catalogue
 *    is scored against English, and anything below MIN_COMPLETENESS is hidden
 *    from the picker rather than listed and disappointing. Partial locales
 *    between the thresholds are listed with their percentage, so the choice is
 *    informed rather than a surprise.
 *
 * 2. Some things must NOT be translated, and the catalogues reflect that. File
 *    extensions (.srwb, .ipynb, .py) and kernel names (Python, Bash, Prolog)
 *    are identifiers, not prose — they stay literal in every locale. In a
 *    right-to-left script this matters visibly: the Latin extension keeps its
 *    own direction inside the surrounding RTL sentence, and translators are
 *    told so in the catalogue itself rather than having to guess.
 */

(function () {
    'use strict';

    const STORAGE_KEY = 'scirepl_language';

    /**
     * Opt-in to seeing unreviewed translations in the picker.
     *
     * The review gate keeps drafts away from ordinary users, but it also kept
     * them away from the people who have to review them: before this, the only
     * way to see a draft was window.i18n.activate('ar') in a console, which is
     * no use to the native speaker whose judgement we actually need.
     *
     * Drafts are offered and auto-detected, because someone who cannot read
     * English cannot use the app at all, and a reviewed-only gate would have
     * handed every one of them an English interface. An unreviewed translation
     * they can read beats a polished one they cannot.
     *
     * Completeness is the gate that remains: below MIN_COMPLETENESS a locale is
     * still withheld, since a 17%-translated UI is worse than English rather
     * than better. Drafts are labelled as under review wherever they are shown.
     *
     * The privacy policy is the one place this is not enough. It is machine
     * translated like everything else, so it carries a notice — in the reader's
     * own language — saying the translation is informational and the English
     * text is the official policy. See renderTranslationNotice().
     */
    const SHOW_DRAFTS_KEY = 'scirepl_i18n_show_drafts';
    const BASE_LOCALE = 'en';

    /** Below this, a locale is not offered at all. */
    const MIN_COMPLETENESS = 0.8;
    /** Between this and 1.0 it is offered, but labelled partial. */
    const PARTIAL_THRESHOLD = 1.0;

    /**
     * Locales that ship with the app. `dir` drives document direction.
     * `endonym` is the language's own name for itself — a picker that says
     * "Spanish" is no use to someone who only reads Spanish.
     */
    /**
     * Filled from i18n/manifest.json, which is generated by
     * scripts/build-i18n-manifest.mjs.
     *
     * This used to be a hard-coded list, and init() fetched every catalogue at
     * startup purely to compute completeness scores. That is two requests today
     * and twenty at twenty locales, on every launch, to answer a question whose
     * answer never changes between builds. The manifest answers it once, so the
     * app fetches one small index plus the single catalogue it actually uses.
     *
     * Catalogues are still bundled rather than downloaded on demand: a locale is
     * ~11 KB gzipped against ~92 MB of shipped runtimes, so lazy-fetching them
     * would save under 1% of payload while adding a consent question before the
     * privacy policy has even been shown.
     */
    let LOCALES = [
        // Fallback if the manifest is unavailable; English alone always works.
        { code: 'en', endonym: 'English', dir: 'ltr', status: 'reviewed', completeness: 1 },
    ];

    /**
     * A locale is only offered once a human who reads it has signed it off.
     *
     * A machine translation can be complete and still be wrong in ways the
     * completeness score cannot see — register, terminology, or simply being
     * inaccurate. So a catalogue may declare `"status": "draft"` in its
     * __meta, land in the repository, and be reviewable, without being
     * offered to users until the status changes to "reviewed".
     *
     * Draft locales remain selectable through the RTL/preview mechanism below,
     * which is how a reviewer looks at one in situ.
     */
    const REVIEWED = 'reviewed';

    /**
     * Pseudo-locale for checking right-to-left layout without a translation.
     *
     * Layout and language are separate problems, and mixing them wastes a
     * reviewer's time: a native speaker asked to check an Arabic build should be
     * reporting translation issues, not that a margin is on the wrong side.
     * This renders the English strings right-to-left so the layout can be fixed
     * first, independently.
     *
     *   window.i18n.activate('en-x-rtl')
     */
    const RTL_PREVIEW = 'en-x-rtl';

    /**
     * Inline markup permitted inside a translated string. Deliberately tiny:
     * enough for a code sample, an emphasis and a documentation link, and
     * nothing that can execute or load anything.
     */
    const INLINE_TAGS = new Set(['CODE', 'STRONG', 'EM', 'B', 'I', 'BR', 'A', 'SPAN']);

    function sanitiseInline(html) {
        const tpl = document.createElement('template');
        tpl.innerHTML = html;
        const walk = (node) => {
            for (const child of Array.from(node.childNodes)) {
                if (child.nodeType === Node.TEXT_NODE) continue;
                if (child.nodeType !== Node.ELEMENT_NODE || !INLINE_TAGS.has(child.tagName)) {
                    // Keep the words, drop the element.
                    child.replaceWith(...Array.from(child.childNodes || []));
                    continue;
                }
                for (const attr of Array.from(child.attributes)) {
                    const ok = child.tagName === 'A' && attr.name === 'href'
                        && /^(https?:|mailto:|#)/i.test(attr.value.trim());
                    if (!ok) child.removeAttribute(attr.name);
                }
                if (child.tagName === 'A') {
                    child.setAttribute('rel', 'noopener noreferrer');
                    child.setAttribute('target', '_blank');
                }
                walk(child);
            }
        };
        walk(tpl.content);
        return tpl.innerHTML;
    }

    class I18n {
        constructor() {
            this.catalogues = {};      // code -> { key: string }
            this.completeness = {};    // code -> 0..1
            this.current = BASE_LOCALE;
            this._ready = null;
        }

        /* --------------------------- detection --------------------------- */

        /** Stored choice, or 'auto'. */
        getPreference() {
            return localStorage.getItem(STORAGE_KEY) || 'auto';
        }

        setPreference(code) {
            if (code === 'auto') localStorage.removeItem(STORAGE_KEY);
            else localStorage.setItem(STORAGE_KEY, code);
        }

        /**
         * Resolve the preference to a locale that actually exists and is
         * complete enough to use. Falls back through the language subtag
         * (es-MX -> es) before giving up on English.
         */
        resolve(preference = this.getPreference()) {
            // Based on the manifest, so this works before any catalogue is
            // fetched — which is the point of having a manifest.
            // Complete enough, and either reviewed or explicitly opted into.
            const usable = (code) => (this.completeness[code] ?? 0) >= MIN_COMPLETENESS
                && LOCALES.some((l) => l.code === code)
                && (this.statusOf(code) === REVIEWED || this.showDrafts());
            // showDrafts() is true by default; see SHOW_DRAFTS_KEY.

            if (preference !== 'auto') {
                if (usable(preference)) return preference;
                const base = String(preference).split('-')[0];
                if (usable(base)) return base;
                return BASE_LOCALE;
            }

            const wanted = navigator.languages && navigator.languages.length
                ? navigator.languages
                : [navigator.language || BASE_LOCALE];

            for (const tag of wanted) {
                if (usable(tag)) return tag;
                const base = String(tag).split('-')[0];
                if (usable(base)) return base;
            }
            return BASE_LOCALE;
        }

        /** What `auto` would pick right now, for showing in the picker. */
        detected() {
            return this.resolve('auto');
        }

        /* ---------------------------- manifest --------------------------- */

        async loadManifest() {
            try {
                const res = await fetch('i18n/manifest.json');
                if (!res.ok) throw new Error(`HTTP ${res.status}`);
                const data = await res.json();
                if (Array.isArray(data.locales) && data.locales.length) {
                    // Replace the contents rather than rebinding. `LOCALES` is
                    // also exposed as i18n.LOCALES, captured once at module load;
                    // reassigning left that reference pointing at the stale
                    // English-only fallback, so anything reading it — a console
                    // session, a test — silently saw the wrong list.
                    LOCALES.length = 0;
                    LOCALES.push(...data.locales);
                    for (const l of LOCALES) {
                        // Seed the scores so resolve() and available() work
                        // before any catalogue has been fetched.
                        this.completeness[l.code] = l.completeness ?? 0;
                    }
                }
                this.manifest = data;
            } catch (e) {
                // English is bundled and always works, so a missing manifest
                // degrades to an English-only picker rather than a failure.
                console.warn('[i18n] manifest unavailable, English only:', e.message);
                this.manifest = null;
            }
            return LOCALES;
        }

        /* --------------------------- catalogues -------------------------- */

        async load(code) {
            if (this.catalogues[code]) return this.catalogues[code];
            try {
                const res = await fetch(`i18n/${code}.json`);
                if (!res.ok) throw new Error(`HTTP ${res.status}`);
                const data = await res.json();
                this.catalogues[code] = data.strings || {};
                // Carried on the catalogue so statusOf() can see it.
                this.catalogues[code].__status = (data.__meta || {}).status;
                // Identifiers that stay English everywhere are declared once, in
                // the base catalogue. Held separately so _score() matches what
                // scripts/build-i18n-manifest.mjs computed — two scorers
                // disagreeing would put one number in the manifest and a
                // different one in the picker.
                if (code === BASE_LOCALE) this.sharedLiteral = data.__literal || [];
                this._score(code);
                return this.catalogues[code];
            } catch (e) {
                console.warn(`[i18n] could not load '${code}':`, e.message);
                this.catalogues[code] = null;
                this.completeness[code] = 0;
                return null;
            }
        }

        /**
         * Fraction of English keys that this locale translates to something
         * different. A value identical to English counts as untranslated —
         * which is the check that stops a stub catalogue looking complete.
         *
         * Keys marked `!` in the catalogue's `literal` list are exempt: they are
         * meant to be identical (file extensions, product names), so counting
         * them as untranslated would understate real coverage.
         */
        _score(code) {
            const base = this.catalogues[BASE_LOCALE];
            const target = this.catalogues[code];
            if (!base || !target) { this.completeness[code] = 0; return; }
            if (code === BASE_LOCALE) { this.completeness[code] = 1; return; }

            const literal = new Set([...(this.sharedLiteral || []), ...(target.__literal || [])]);
            const keys = Object.keys(base).filter((k) => !k.startsWith('__') && !literal.has(k));
            if (!keys.length) { this.completeness[code] = 1; return; }

            let done = 0;
            for (const k of keys) {
                const v = target[k];
                if (typeof v === 'string' && v.trim() && v !== base[k]) done++;
            }
            this.completeness[code] = done / keys.length;
        }

        /* ---------------------------- lookup ----------------------------- */

        /**
         * Translate. Falls back to English, then to the key itself, so a missing
         * string degrades to something readable rather than blank.
         *
         * `t('menu.appearance')` or with substitution:
         * `t('appearance.scalePercent', { percent: 150 })`
         */
        t(key, vars) {
            const cat = this.catalogues[this.current] || {};
            const base = this.catalogues[BASE_LOCALE] || {};
            let out = cat[key];
            if (typeof out !== 'string' || !out) out = base[key];
            if (typeof out !== 'string') return key;
            if (vars) {
                out = out.replace(/\{(\w+)\}/g, (m, name) =>
                    (Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m));
            }
            return out;
        }

        /* --------------------------- activation -------------------------- */

        /** Whether unreviewed translations are shown in the picker. */
        /**
         * Unreviewed translations are shown by default. The setting exists so a
         * reviewer can turn them *off* to compare against English, not to opt in.
         */
        showDrafts() {
            return localStorage.getItem(SHOW_DRAFTS_KEY) !== '0';
        }

        setShowDrafts(on) {
            if (on) localStorage.removeItem(SHOW_DRAFTS_KEY);
            else localStorage.setItem(SHOW_DRAFTS_KEY, '0');
        }

        /* ------------------------ domain catalogues ----------------------- */

        /**
         * Privacy text is a legal document, and every non-English rendering of
         * it is machine translated. Fetch the notice that says so, in the
         * reader's language — a warning they cannot read is not a warning.
         */
        async loadDomain(code, domain) {
            this.domains = this.domains || {};
            const id = `${domain}.${code}`;
            if (id in this.domains) return this.domains[id];
            try {
                const res = await fetch(`i18n/${domain}.${code}.json`);
                if (!res.ok) throw new Error(`HTTP ${res.status}`);
                this.domains[id] = (await res.json()).strings || {};
            } catch {
                this.domains[id] = null;
            }
            return this.domains[id];
        }

        /**
         * Put the "this translation is informational" notice into the privacy
         * dialog, or take it away again when the reader is back on English.
         */
        async renderTranslationNotice(rootEl = document) {
            const host = rootEl.querySelector
                ? rootEl.querySelector('#privacy-translation-notice') : null;
            if (!host) return;
            if (this.current === BASE_LOCALE) {
                host.hidden = true;
                host.textContent = '';
                return;
            }
            const strings = await this.loadDomain(this.current, 'privacy');
            const notice = (strings && strings['privacy.translationNotice'])
                // Falling back to English is not ideal, but a notice in the
                // wrong language still beats a translated policy with none.
                || 'This translation is provided for information only. '
                   + 'The English version is the official privacy policy.';
            host.textContent = notice;
            host.hidden = false;
        }

        /** Locales worth showing in the picker, with their status. */
        available() {
            return LOCALES
                .map((l) => ({
                    ...l,
                    completeness: this.completeness[l.code] ?? 0,
                }))
                // Complete *and* reviewed. A draft stays in the repository and
                // stays out of the picker until someone who reads it has checked
                // it — unless the reviewer has explicitly asked to see drafts.
                .filter((l) => l.code === BASE_LOCALE
                    || (l.completeness >= MIN_COMPLETENESS
                        && (this.statusOf(l.code) === REVIEWED || this.showDrafts())))
                .map((l) => ({
                    ...l,
                    draft: l.code !== BASE_LOCALE && this.statusOf(l.code) !== REVIEWED,
                    partial: l.completeness < PARTIAL_THRESHOLD && l.code !== BASE_LOCALE,
                }));
        }

        localeInfo(code) {
            if (code === RTL_PREVIEW) {
                return { code: RTL_PREVIEW, endonym: 'English (RTL preview)', dir: 'rtl', status: 'draft' };
            }
            return LOCALES.find((l) => l.code === code) || LOCALES[0];
        }

        /** Declared review status, defaulting to draft for anything unstated. */
        statusOf(code) {
            if (code === BASE_LOCALE) return REVIEWED;
            const declared = (this.catalogues[code] || {}).__status;
            const registered = (LOCALES.find((l) => l.code === code) || {}).status;
            return declared || registered || 'draft';
        }

        /**
         * Review status of a domain catalogue, which may lag the UI.
         * Privacy text is legal copy: a machine draft is informational until a
         * qualified reviewer signs it off, regardless of how complete it looks.
         */
        domainStatusOf(code, domain) {
            const entry = LOCALES.find((l) => l.code === code);
            return (entry && entry.domains && entry.domains[domain] || {}).status || 'draft';
        }

        /** Load what is needed and apply the resolved locale to the document. */
        async init() {
            if (this._ready) return this._ready;
            this._ready = (async () => {
                await this.loadManifest();
                await this.load(BASE_LOCALE);
                await this.activate(this.resolve());
            })();
            return this._ready;
        }

        async activate(code) {
            if (code === RTL_PREVIEW) {
                // Reuse the base strings; only the direction changes.
                await this.load(BASE_LOCALE);
                this.catalogues[RTL_PREVIEW] = this.catalogues[BASE_LOCALE];
                this.completeness[RTL_PREVIEW] = 1;
            }
            await this.load(code);
            if (!this.catalogues[code]) code = BASE_LOCALE;
            this.current = code;

            const info = this.localeInfo(code);
            const root = document.documentElement;
            root.setAttribute('lang', code);
            root.setAttribute('dir', info.dir);

            this.applyToDom();
            // The policy's official-language notice follows the locale, and must
            // not wait for the dialog to be opened — it is part of the text.
            // Awaited so the DOM is consistent by the time i18n:changed fires;
            // without this, switching locales twice quickly left the previous
            // language's notice sitting above the new policy text.
            await this.renderTranslationNotice();
            document.dispatchEvent(new CustomEvent('i18n:changed', { detail: { code } }));
        }

        /**
         * Translate everything currently in the DOM.
         *
         * Markup opts in with `data-i18n` (text), `data-i18n-title`,
         * `data-i18n-placeholder`, or `data-i18n-aria-label`. Untagged elements
         * are left alone, so this can be adopted incrementally rather than
         * needing every string extracted before anything works.
         */
        applyToDom(rootEl = document) {
            for (const el of rootEl.querySelectorAll('[data-i18n]')) {
                const key = el.getAttribute('data-i18n');
                const translated = this.t(key);
                if (translated !== key) el.textContent = translated;
            }
            // Strings whose English contains inline markup — <code>%pip install</code>,
            // a <strong> emphasis, a documentation link. textContent would delete
            // the markup, so these are set as HTML through a strict allowlist.
            // Catalogues are bundled repo assets rather than user input, but a
            // translator pasting from a rich-text editor is an ordinary accident,
            // and this is the one place translated data reaches innerHTML.
            for (const el of rootEl.querySelectorAll('[data-i18n-html]')) {
                const key = el.getAttribute('data-i18n-html');
                const translated = this.t(key);
                if (translated !== key) el.innerHTML = sanitiseInline(translated);
            }
            const attrs = [
                ['data-i18n-title', 'title'],
                ['data-i18n-placeholder', 'placeholder'],
                ['data-i18n-aria-label', 'aria-label'],
            ];
            for (const [dataAttr, target] of attrs) {
                for (const el of rootEl.querySelectorAll(`[${dataAttr}]`)) {
                    const key = el.getAttribute(dataAttr);
                    const translated = this.t(key);
                    if (translated !== key) el.setAttribute(target, translated);
                }
            }
        }
    }

    const i18n = new I18n();
    i18n.LOCALES = LOCALES;
    i18n.MIN_COMPLETENESS = MIN_COMPLETENESS;
    i18n.BASE_LOCALE = BASE_LOCALE;
    i18n.RTL_PREVIEW = RTL_PREVIEW;
    i18n.REVIEWED = REVIEWED;

    window.i18n = i18n;
    window.t = (key, vars) => i18n.t(key, vars);

    i18n.init().catch((e) => console.warn('[i18n] init failed:', e));
})();
